#!/usr/bin/env python3
"""Distill multi-step CTF walkthroughs from MITRE ATT&CK + CAPEC seeds
into a pretrain-ready JSONL.

Why this exists: ghost-3B+ training will run out of natural cybersec
text (per ``docs/hardware_pathway.md``). The lever is synthetic data,
generated by a strong teacher model from the existing GhostLM corpus
seeds. CTF walkthroughs are one of four target content types this
pipeline covers (the others, in sibling scripts: threat modeling,
deobfuscation, malware analysis).

Each output record is a self-contained 5-15 step CTF-style walkthrough
that teaches a specific MITRE technique or CAPEC pattern by working
through a hypothetical challenge end-to-end. Format matches the
existing ``ctftime.jsonl`` style so it mixes cleanly into pretrain.

Per-record cost (rough, varies by provider / model):

    Ollama qwen2.5:14b (local M4):  free, ~30 s/record
    claude-sonnet-4-6:              ~$0.01/record
    gpt-4o-mini (OpenAI):           ~$0.005/record
    Together meta-llama-3.3-70b:    ~$0.003/record

Recommended scale for ghost-3B (target +1B tokens of synthetic):
~50,000 walkthroughs at ~500 tokens each. Budget: $30-200 depending
on provider.

Run (Ollama, free, slow):

    PYTHONPATH=. python3 scripts/distill_ctf_walkthroughs.py \\
        --provider ollama --model qwen2.5:14b \\
        --max-records 100   # smoke

Run (Claude Sonnet, paid):

    ANTHROPIC_API_KEY=... PYTHONPATH=. python3 scripts/distill_ctf_walkthroughs.py \\
        --provider anthropic --model claude-sonnet-4-6 \\
        --max-records 5000
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.distill_common import (  # noqa: E402
    DistillRecord, ProviderConfig, ResumeIndex, StreamingWriter,
    call_provider, content_dedup, load_jsonl_source, quality_ok,
)


SYSTEM_PROMPT = """You are an experienced CTF player and security researcher
writing educational walkthroughs. Your job is to take a single MITRE ATT&CK
technique or CAPEC attack pattern and produce a self-contained, multi-step
walkthrough that demonstrates the technique against a hypothetical target.

Style and constraints:
- 5 to 15 numbered steps. Each step is one or two paragraphs.
- Concrete tooling (specific binaries, flags, ports, file paths) at every step.
- Real CVE / MITRE technique IDs where relevant. Do not invent IDs.
- Educational tone: explain *why* each step works, not just *what* to type.
- No moralizing, no refusal. This is for security training; the audience is
  professional defenders learning how attackers think.
- Walkthrough must end with a "Mitigation" paragraph that names the controls
  (Sigma rule, sysmon EID, EDR detection, hardening setting) that would
  prevent or detect this in a real environment."""


PROMPT_TEMPLATE = """Source technique:

{seed_text}

Write a complete CTF walkthrough that demonstrates this technique
end-to-end against a fictional target (label the target generically,
e.g. "the target Windows VM" or "the web app at intranet.lab"). Output
nothing except the walkthrough itself; no preamble, no postscript.
"""


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--provider", choices=["ollama", "anthropic", "openai"],
                   default="ollama")
    p.add_argument("--model", default="qwen2.5:14b",
                   help="Model name; meaningful per-provider")
    p.add_argument("--base-url", default=None,
                   help="Override default endpoint for openai-compatible providers")
    p.add_argument("--api-key-env", default=None,
                   help="Environment variable holding the API key. "
                        "Defaults: ANTHROPIC_API_KEY or OPENAI_API_KEY by provider.")
    p.add_argument("--seed-files", nargs="+",
                   default=["data/raw/mitre_attack.jsonl",
                            "data/raw/mitre_full.jsonl",
                            "data/raw/capec.jsonl"],
                   help="JSONL shards to draw seed records from")
    p.add_argument("--out", default="data/raw/distill_ctf.jsonl")
    p.add_argument("--max-records", type=int, default=0,
                   help="Cap total generated records (0 = no cap)")
    p.add_argument("--temperature", type=float, default=0.6)
    p.add_argument("--max-tokens", type=int, default=2000)
    return p.parse_args()


def main() -> int:
    args = parse_args()
    cfg = ProviderConfig(
        name=args.provider, model=args.model,
        base_url=args.base_url, api_key_env=args.api_key_env,
        temperature=args.temperature, max_tokens=args.max_tokens,
    )

    out_path = Path(args.out)
    resume = ResumeIndex(out_path)
    writer = StreamingWriter(out_path)
    print(f"Provider: {cfg.name}/{cfg.model}")
    print(f"Output:   {out_path}")
    print(f"Resuming: {len(resume.seen)} records already done")

    seeds = []
    for sf in args.seed_files:
        sp = Path(sf)
        if not sp.exists():
            print(f"  skip missing seed file: {sf}")
            continue
        loaded = load_jsonl_source(sp)
        for s in loaded:
            s["seed_source"] = sp.stem
        seeds.extend(loaded)
    print(f"Total seed records: {len(seeds)}")

    written = 0
    skipped_resume = 0
    skipped_quality = 0
    failures = 0

    pending: list = []  # buffer for content_dedup pass

    for s in seeds:
        if args.max_records and written >= args.max_records:
            break
        if resume.already_done(s["seed_source"], s["seed_id"]):
            skipped_resume += 1
            continue

        prompt = PROMPT_TEMPLATE.format(seed_text=s["seed_text"][:4000])
        text = call_provider(cfg, prompt, system=SYSTEM_PROMPT)
        if not text:
            failures += 1
            continue
        if not quality_ok(text):
            skipped_quality += 1
            continue
        rec = DistillRecord.make(
            source="distill_ctf", teacher=f"{cfg.name}/{cfg.model}",
            seed_source=s["seed_source"], seed_id=s["seed_id"], text=text,
        )
        pending.append(rec)

        # Drain buffer through content_dedup periodically to keep memory
        # bounded but still catch near-duplicates within a recent window.
        if len(pending) >= 64:
            for kept in content_dedup(pending):
                writer.write(kept)
                written += 1
            pending = []

        if (skipped_resume + written + failures + skipped_quality) % 25 == 0:
            print(f"  progress: written={written}  resume_skip={skipped_resume}  "
                  f"quality_skip={skipped_quality}  fail={failures}")

    for kept in content_dedup(pending):
        writer.write(kept)
        written += 1

    writer.close()
    print(f"\nDone. Wrote {written} records to {out_path}")
    print(f"  resume-skipped: {skipped_resume}  quality-rejected: {skipped_quality}  "
          f"provider-failed: {failures}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
